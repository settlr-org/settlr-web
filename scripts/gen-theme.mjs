// Generates app/theme.generated.css and app/icon.svg from theme/theme.json (the single colour
// source of truth shared with settlr-android). Both outputs are gitignored; dev/build/typecheck/test
// run this first. Never add colour literals to CSS or TSX: add a token to theme.json instead.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const theme = JSON.parse(readFileSync(join(root, "theme/theme.json"), "utf8"));
const HEX = /^#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/;

const kebab = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const keys = Object.keys(theme.modes.light);
for (const [mode, tokens] of Object.entries(theme.modes)) {
  const missing = keys.filter((k) => !(k in tokens));
  const extra = Object.keys(tokens).filter((k) => !keys.includes(k));
  if (missing.length || extra.length) {
    throw new Error(
      `theme.json: mode "${mode}" key mismatch (missing ${missing}, extra ${extra})`,
    );
  }
}
// "amoled" is a partial override of the dark mode used by Android only: every key must exist in dark.
for (const k of Object.keys(theme.amoled ?? {})) {
  if (!(k in theme.modes.dark))
    throw new Error(`theme.json: amoled token "${k}" is not a dark token`);
}
for (const [k, v] of [
  ...Object.entries(theme.modes).flatMap(([, t]) => Object.entries(t)),
  ...Object.entries(theme.amoled ?? {}),
  ...Object.entries(theme.brand),
]) {
  if (!HEX.test(v))
    throw new Error(`theme.json: ${k} = ${v} is not #RRGGBB or #RRGGBBAA`);
}

const block = (selector, tokens) =>
  `${selector} {\n${Object.entries(tokens)
    .map(([k, v]) => `  --st-${kebab(k)}: ${v.toLowerCase()};`)
    .join("\n")}\n}\n`;

const css =
  `/* Generated by scripts/gen-theme.mjs from theme/theme.json (${theme.name}). Do not edit. */\n` +
  block(":root", { ...theme.modes.light, ...theme.brand }) +
  block(':root[data-theme="dark"]', theme.modes.dark);
writeFileSync(join(root, "app/theme.generated.css"), css);

const { launcherBackground: bg, launcherForeground: fg } = theme.brand;
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="Settlr">
  <rect width="64" height="64" rx="16" fill="${bg}"/>
  <circle cx="32" cy="32" r="13" fill="none" stroke="${fg}" stroke-width="3"/>
</svg>
`;
writeFileSync(join(root, "app/icon.svg"), icon);
console.log(
  `theme: generated app/theme.generated.css and app/icon.svg (${theme.name})`,
);
